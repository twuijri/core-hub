#!/usr/bin/env node
// The agents' own marks (Hermes, Claude Code, Codex, …) for the iOS and Android apps, from the one
// source the web draws them from: packages/web/src/ui/brand/marks.tsx (its paths, its `MARKS` map
// of catalog slug → mark). Nothing is copied by hand, so a mark changed for the web changes here.
//
//   node scripts/icons/agent-marks-mobile.mjs           # write
//   node scripts/icons/agent-marks-mobile.mjs --check   # exit 1 when a committed file differs
//
// - iOS: `Assets.xcassets/AgentMarks/<slug>.imageset/<slug>.svg`, a template vector (the folder
//   is a namespace: `Image("AgentMarks/<slug>")`), and `CoreHub/Generated/AgentMarks.swift`, the
//   slugs the app carries.
// - Android: `res/drawable/agent_mark_<slug>.xml` vector drawables, and
//   `hub/core/android/ui/components/AgentMarks.kt`, slug → drawable.
//
// A mark is one colour on a 24 grid and takes the text colour, as on the web. Their owners'
// trademarks: see the header of marks.tsx (they only name the agent they identify).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const check = process.argv.includes('--check');
const sourceRel = 'packages/web/src/ui/brand/marks.tsx';
const source = readFileSync(path.join(repo, sourceRel), 'utf8');

/** Each `export const MarkX = (p) => ( <Mark …> … </Mark> );` as its paths and its drawing. */
function components() {
  const found = new Map();
  const re =
    /export const (Mark\w+) = \(p: MarkProps\) => \(\s*<Mark([^>]*)>([\s\S]*?)<\/Mark>\s*\);/g;
  for (const [, name, attrs, body] of source.matchAll(re)) {
    const stroked = /fill="none"/.test(attrs);
    const width = Number(/strokeWidth=\{([\d.]+)\}/.exec(attrs)?.[1] ?? 2);
    const paths = [...body.matchAll(/d="([^"]+)"/g)].map((m) => m[1]);
    if (paths.length === 0) throw new Error(`${sourceRel}: ${name} has no path`);
    found.set(name, { stroked, width, paths });
  }
  return found;
}

/** The `MARKS` map: catalog slug → component. */
function slugs() {
  const block = /const MARKS[^{]*\{([\s\S]*?)\n\};/.exec(source)?.[1];
  if (!block) throw new Error(`${sourceRel}: no MARKS map`);
  return [...block.matchAll(/'?([\w-]+)'?:\s*(Mark\w+)/g)].map(([, slug, component]) => ({
    slug,
    component,
  }));
}

/**
 * Path data written out with every number separated. The web's paths pack an arc's two flags
 * against the next number (`a.5.5 0 01.1.2`), which browsers read but some vector parsers do not;
 * the shape is unchanged.
 */
function normalise(d) {
  const out = [];
  let i = 0;
  let command = '';
  let argIndex = 0;
  const number = /^[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?/;
  while (i < d.length) {
    const c = d[i];
    if (/[\s,]/.test(c)) {
      i++;
      continue;
    }
    if (/[MmZzLlHhVvCcSsQqTtAa]/.test(c)) {
      command = c;
      argIndex = 0;
      out.push(c);
      i++;
      continue;
    }
    const arc = command === 'A' || command === 'a';
    if (arc && (argIndex % 7 === 3 || argIndex % 7 === 4)) {
      if (c !== '0' && c !== '1') throw new Error(`bad arc flag "${c}" in ${d.slice(0, 40)}…`);
      out.push(c);
      i++;
      argIndex++;
      continue;
    }
    const match = number.exec(d.slice(i));
    if (!match) throw new Error(`cannot read path data at "${d.slice(i, i + 20)}"`);
    out.push(match[0]);
    i += match[0].length;
    argIndex++;
  }
  return out.join(' ').replace(/ ?([MmZzLlHhVvCcSsQqTtAa])(?: |$)/g, '$1');
}

const marks = components();
for (const mark of marks.values()) mark.paths = mark.paths.map(normalise);
const entries = slugs().map(({ slug, component }) => {
  const mark = marks.get(component);
  if (!mark) throw new Error(`${sourceRel}: MARKS names ${component}, which is not defined`);
  return { slug, ...mark };
});

const outputs = new Map();
const put = (rel, text) => outputs.set(rel, Buffer.from(text));
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const header = `Generated by scripts/icons/agent-marks-mobile.mjs from ${sourceRel}; do not edit by hand.`;
const ios = 'apps/ios/CoreHub/Resources/Assets.xcassets/AgentMarks';
const res = 'apps/android/app/src/main/res/drawable';
const androidName = (slug) => `agent_mark_${slug.replace(/-/g, '_')}`;

put(
  `${ios}/Contents.json`,
  json({ info: { author: 'xcode', version: 1 }, properties: { 'provides-namespace': true } }),
);
for (const mark of entries) {
  const svgPaths = mark.paths
    .map((d) =>
      mark.stroked
        ? `<path d="${d}" fill="none" stroke="#000000" stroke-width="${mark.width}" stroke-linecap="round" stroke-linejoin="round"/>`
        : `<path d="${d}" fill="#000000" fill-rule="evenodd" clip-rule="evenodd"/>`,
    )
    .join('');
  put(
    `${ios}/${mark.slug}.imageset/${mark.slug}.svg`,
    `<!-- ${mark.slug} · ${header} -->\n` +
      `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">${svgPaths}</svg>\n`,
  );
  put(
    `${ios}/${mark.slug}.imageset/Contents.json`,
    json({
      images: [{ filename: `${mark.slug}.svg`, idiom: 'universal' }],
      info: { author: 'xcode', version: 1 },
      properties: {
        'preserves-vector-representation': true,
        'template-rendering-intent': 'template',
      },
    }),
  );
  const vectorPaths = mark.paths
    .map((d) =>
      mark.stroked
        ? `    <path\n        android:pathData="${d}"\n        android:fillColor="#00000000"\n` +
          `        android:strokeColor="#FF000000"\n        android:strokeWidth="${mark.width}"\n` +
          `        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />\n`
        : `    <path\n        android:pathData="${d}"\n        android:fillColor="#FF000000"\n` +
          `        android:fillType="evenOdd" />\n`,
    )
    .join('');
  put(
    `${res}/${androidName(mark.slug)}.xml`,
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${mark.slug} · ${header} -->\n` +
      `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n` +
      `    android:width="24dp" android:height="24dp"\n` +
      `    android:viewportWidth="24" android:viewportHeight="24">\n` +
      vectorPaths +
      `</vector>\n`,
  );
}
put(
  'apps/ios/CoreHub/Generated/AgentMarks.swift',
  `// ${header}\n` +
    `// The agents' own marks the app carries, by catalog slug (the web's \`agentMark\`).\n` +
    `import SwiftUI\n\n` +
    `enum AgentMarks {\n` +
    `    static let slugs: Set<String> = [${entries.map((m) => `"${m.slug}"`).join(', ')}]\n\n` +
    `    /// The mark of the agent with this catalog slug, as a template image; nil for one we do not ship.\n` +
    `    static func image(_ slug: String?) -> Image? {\n` +
    `        guard let slug, slugs.contains(slug) else { return nil }\n` +
    `        return Image("AgentMarks/\\(slug)").renderingMode(.template)\n` +
    `    }\n` +
    `}\n`,
);
put(
  'apps/android/app/src/main/java/hub/core/android/ui/components/AgentMarks.kt',
  `// ${header}\n` +
    `package hub.core.android.ui.components\n\n` +
    `import hub.core.android.R\n\n` +
    `/** The agents' own marks the app carries, by catalog slug (the web's \`agentMark\`). */\n` +
    `object AgentMarks {\n` +
    `    val drawables: Map<String, Int> = mapOf(\n` +
    entries.map((m) => `        "${m.slug}" to R.drawable.${androidName(m.slug)},\n`).join('') +
    `    )\n\n` +
    `    /** The mark of the agent with this catalog slug; null for one we do not ship. */\n` +
    `    fun of(slug: String?): Int? = slug?.let { drawables[it] }\n` +
    `}\n`,
);

function stale() {
  const found = [];
  const iosDir = path.join(repo, ios);
  const slugSet = new Set(entries.map((m) => m.slug));
  if (existsSync(iosDir)) {
    for (const entry of readdirSync(iosDir)) {
      if (entry.endsWith('.imageset') && !slugSet.has(entry.replace(/\.imageset$/, '')))
        found.push(`${ios}/${entry}`);
    }
  }
  const wanted = new Set(entries.map((m) => `${androidName(m.slug)}.xml`));
  for (const entry of readdirSync(path.join(repo, res))) {
    if (entry.startsWith('agent_mark_') && !wanted.has(entry)) found.push(`${res}/${entry}`);
  }
  return found;
}

let bad = 0;
if (check) {
  for (const [rel, data] of outputs) {
    const file = path.join(repo, rel);
    if (!existsSync(file) || !readFileSync(file).equals(data)) {
      console.error(`agent-marks: ${rel} is out of date`);
      bad++;
    }
  }
  for (const rel of stale()) {
    console.error(`agent-marks: ${rel} is no longer a mark`);
    bad++;
  }
  if (bad) {
    console.error(
      'agent-marks: run node scripts/icons/agent-marks-mobile.mjs and commit the result',
    );
    process.exit(1);
  }
} else {
  for (const rel of stale()) rmSync(path.join(repo, rel), { recursive: true, force: true });
  for (const [rel, data] of outputs) {
    const file = path.join(repo, rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, data);
  }
}
console.log(
  `agent-marks: ${entries.length} mark(s) ${check ? 'up to date' : 'written'} (${entries.map((m) => m.slug).join(', ')})`,
);
